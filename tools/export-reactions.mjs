// Futnet's point reactions: the spiky player's generated win and loss cycles from
// the complete library (artwork/players/roster/spiky/complete.json, rows "win" and
// "loss", from reactions/study-v2), six 16x24 front-view frames each, as the
// upright layout gfx_actor draws (two 8x16 columns, each a top and a bottom sprite:
// 8 tiles, 128 bytes a frame), into src/reaction_art.c / .h.
// Run: node tools/export-reactions.mjs
import fs from 'node:fs';
import assert from 'node:assert/strict';
const lib = JSON.parse(fs.readFileSync(new URL('../artwork/players/roster/spiky/complete.json', import.meta.url)));
assert.deepEqual(lib.palette.map((p) => p.slice(0, 3)), [[0, 0, 0], [248, 200, 136], [40, 120, 232], [24, 32, 48]], 'the players\' palette order');
const bytes = [], lifts = [], names = [];
for (const name of ['win', 'loss']) {
  const a = lib.animations.find((a) => a.name === name);
  assert.equal(a.frames.length, 6, name);
  for (const f of a.frames) {
    assert.equal(f.rows.length, 24); assert.equal(f.rows[0].length, 16);
    names.push(`${name} ${f.name}`);
    lifts.push(f.lift ?? 0);
    for (const col of [0, 8]) for (const top of [0, 16]) for (let y = top; y < top + 16; y++) {
      let lo = 0, hi = 0;
      for (let x = 0; x < 8; x++) { const v = y < 24 ? Number(f.rows[y][col + x]) || 0 : 0; lo |= (v & 1) << (7 - x); hi |= (v >> 1) << (7 - x); }
      bytes.push(lo, hi);
    }
  }
}
const hex = (a) => { const out = []; for (let i = 0; i < a.length; i += 16) out.push('    ' + a.slice(i, i + 16).map((b) => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ','); return out.join(String.fromCharCode(10)); };
fs.writeFileSync(new URL('../src/reaction_art.h', import.meta.url), `// Generated by tools/export-reactions.mjs: do not edit.
#ifndef REACTION_ART_H
#define REACTION_ART_H
#include <gb/gb.h>
// Twelve frames, 128 bytes each: ${names.join(', ')}.
#define REACTION_ART_FRAMES 12
#define REACTION_ART_LOSS 6  // the first loss frame
// The library's jump lift for each frame, px.
#define REACTION_ART_LIFTS { ${lifts.join(', ')} }
// Copies every frame's tiles to dst (REACTION_ART_FRAMES * 128 bytes).
void reaction_art_load(uint8_t *dst) BANKED;
#endif
`);
fs.writeFileSync(new URL('../src/reaction_art.c', import.meta.url), `// Generated by tools/export-reactions.mjs: do not edit.
#pragma bank 255
#include <string.h>
#include "reaction_art.h"
static const uint8_t reaction_tiles[${bytes.length}] = {
${hex(bytes)}
};
void reaction_art_load(uint8_t *dst) BANKED {
    memcpy(dst, reaction_tiles, sizeof reaction_tiles);
}
`);
console.log(`reactions: ${names.length} frames, lifts ${lifts.join(' ')}, ${bytes.length} bytes`);
