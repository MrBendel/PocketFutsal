// Converts the burst effects (artwork/BURST_VFX, a paid pack: gitignored, never
// committed) into sprite tiles committed as src/vfx_tiles.c and src/vfx_tiles.h, so
// the public build has them without the pack. Run by hand when the effects change:
//   node tools/export-vfx.mjs [path to the pack]
// The GB Studio (_GBS) sheets: green is see-through, then light, mid, dark (sprite
// colors 1, 2, 3). Frames are cut into 8x16 columns (8x16 sprite mode); identical
// columns are stored once, and empty ones aren't drawn at all.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodePng } from './assets.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PACK = process.argv[2] || path.join(ROOT, 'artwork', 'BURST_VFX');
const FIRST_TILE = 32;  // sprite tiles (VRAM bank 0) from here: after the ball, shadows and markers
const LO_TILES = 96;    // ... up to 127 (128-159 are the background's and the HUD's sprites)
const HI_TILE = 160;    // then on from here, to 255
const SPRITES = 8;      // sprites OAM_VFX on: no frame may have more columns than this

// id, sheet, frame size, frames held for (frames of play), sprite palette (gfx.h).
const EFFECTS = [
  { id: 'SLAM', file: 'Hit/Hit_Medium_A_GBS', w: 32, h: 32, hold: 3, pal: 'SPR_PAL_POWER' },   // a slam
  { id: 'FIRE', file: 'Hit/Hit_Small_A_GBS', w: 16, h: 16, hold: 3, pal: 'SPR_PAL_POWER' },    // a strike on fire
  { id: 'DUST', file: 'Dust/Dust_Small_A_GBS', w: 24, h: 16, hold: 5, pal: 'SPR_PAL_BALL' },   // a slide, a knockdown
  { id: 'SPARK', file: 'Sparks/Sparks_Small_A_GBS', w: 16, h: 16, hold: 3, pal: 'SPR_PAL_BALL' }, // the net
  { id: 'SPRAY', file: 'Sparks/Sparks_Medium_A_GBS', w: 48, h: 32, crop: 40, hold: 4, pal: 'SPR_PAL_POWER' }, // a slam lands
];

const color = (r, g, b) => (r === 101 && g === 255 && b === 0) ? 0 : r > 200 ? 1 : r > 100 ? 2 : 3;

const columns = [];  // 32 bytes each (two 8x8 tiles)
const colIndex = new Map();
const fx = [], cells = [];
for (const e of EFFECTS) {
  const png = decodePng(fs.readFileSync(path.join(PACK, e.file + '.png')));
  const frames = Math.floor(png.width / e.w), cols = (e.crop || e.w) / 8, rows = e.h / 16;
  fx.push({ ...e, first: cells.length / (cols * rows) | 0, cellAt: cells.length, frames, cols, rows });
  for (let f = 0; f < frames; f++) for (let r = 0; r < rows; r++) for (let c = 0; c < cols; c++) {
    const bytes = [];
    let any = false;
    for (let y = 0; y < 16; y++) {
      let lo = 0, hi = 0;
      for (let x = 0; x < 8; x++) {
        const px = f * e.w + c * 8 + x, py = r * 16 + y, i = (py * png.width + px) * 4;
        const v = color(png.rgba[i], png.rgba[i + 1], png.rgba[i + 2]);
        if (v) any = true;
        lo |= (v & 1) << (7 - x);
        hi |= (v >> 1) << (7 - x);
      }
      bytes.push(lo, hi);
    }
    if (!any) { cells.push(0xff); continue; }
    const key = bytes.join(',');
    if (!colIndex.has(key)) { colIndex.set(key, columns.length); columns.push(bytes); }
    const t = colIndex.get(key) * 2;
    cells.push(t < LO_TILES ? FIRST_TILE + t : HI_TILE + t - LO_TILES);
  }
  for (let f = 0; f < frames; f++) {
    const n = cells.slice(cells.length - (frames - f) * cols * rows, cells.length - (frames - f - 1) * cols * rows).filter((c) => c !== 0xff).length;
    if (n > SPRITES) throw new Error(`${e.id} frame ${f}: ${n} columns, more than ${SPRITES} sprites`);
  }
}
const tileCount = columns.length * 2;
if (tileCount > LO_TILES + 256 - HI_TILE) throw new Error(`too many tiles: ${tileCount}`);
const hex = (b) => '0x' + b.toString(16).toUpperCase().padStart(2, '0');
const note = '// Generated by tools/export-vfx.mjs from the burst effects pack. Do not edit.\n';
fs.writeFileSync(path.join(ROOT, 'src', 'vfx_tiles.c'), `#pragma bank 255
${note}#include <gb/gb.h>
#include "vfx_tiles.h"
BANKREF(vfx_tiles)
const uint8_t vfx_tiles[] = {
${columns.map((c) => '    ' + c.map(hex).join(', ') + ',').join('\n')}
};
`);
fs.writeFileSync(path.join(ROOT, 'src', 'vfx_tiles.h'), `${note}#ifndef VFX_TILES_H
#define VFX_TILES_H
#include <stdint.h>
#include <gb/gb.h>
BANKREF_EXTERN(vfx_tiles)
extern const uint8_t vfx_tiles[];
#define VFX_FIRST_TILE ${FIRST_TILE}
#define VFX_TILE_COUNT ${tileCount}
#define VFX_LO_TILES ${Math.min(tileCount, LO_TILES)}  // from VFX_FIRST_TILE; the rest from VFX_HI_TILE
#define VFX_HI_TILE ${HI_TILE}
${EFFECTS.map((e, k) => `#define VFX_${e.id} ${k}`).join('\n')}
#define VFX_COUNT ${EFFECTS.length}
#define VFX_SPRITES_MAX ${SPRITES}
#endif

#ifdef VFX_TABLES
// Each effect: its first cell, frames, columns, rows of 16 px, frames held, palette.
// Cells: a frame's 8x16 columns, row by row: the first tile, or 0xFF (empty).
static const uint8_t vfx_fx[][6] = {
${fx.map((e) => `    {${e.cellAt}, ${e.frames}, ${e.cols}, ${e.rows}, ${e.hold}, ${e.pal}},  // ${e.id}`).join('\n')}
};
static const uint8_t vfx_cells[] = {
${fx.map((e) => '    ' + cells.slice(e.cellAt, e.cellAt + e.frames * e.cols * e.rows).map((v) => v).join(', ') + ',  // ' + e.id).join('\n')}
};
#endif
`);
console.log(`vfx: ${EFFECTS.length} effects, ${columns.length} columns (${tileCount} tiles from ${FIRST_TILE}), ${cells.filter((c) => c === 0xff).length} of ${cells.length} cells empty`);
